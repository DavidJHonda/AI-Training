import wave, numpy as np, sys
SR=48000; SPF=1600
def load(i):
    w=wave.open(f'r{i}.wav'); return np.frombuffer(w.readframes(w.getnframes()),np.int16).astype(float)
A={i:load(i) for i in (1,2,3)}
def db(x): return 20*np.log10(np.sqrt(np.mean(x*x))+1e-9)
def best(r,a,b):
    """frame boundary in [a,b] s with the quietest 40 ms around it"""
    x=A[r]; out=[]
    for f in range(int(np.ceil(a*30)),int(b*30)+1):
        s=f*SPF; out.append((db(x[s-960:s+960]),f))
    v,f=min(out); return f, f/30, round(v,1)
