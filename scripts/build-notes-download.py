#!/usr/bin/env python3
"""Package the notes PNG for downloads from file:// course previews.

Hosted pages fetch the PNG directly. Local previews load this script only when
saving the notes, because browsers block fetch() of local image files.
"""
import base64
from pathlib import Path

root = Path(__file__).resolve().parents[1]
image = root / 'packets/ai-replaces-school-notes.png'
output = image.with_name('ai-replaces-school-notes-data.js')
encoded = base64.b64encode(image.read_bytes()).decode('ascii')
output.write_text('// Generated by scripts/build-notes-download.py. Do not edit.\n'
                  'window.MESSY_NOTES_PNG_BASE64 =\n' +
                  ' +\n'.join('"' + encoded[i:i + 16384] + '"'
                              for i in range(0, len(encoded), 16384)) + ';\n')
print(f'Generated {output.name} from {image.name}')
