// Browser checks for typed burger predictions, calendar math, and every reveal.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const {spawn} = require('node:child_process');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || '/Users/davidobrien/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:8796';
(async () => {
  const server = process.env.BASE_URL ? null : spawn('python3', ['-m', 'http.server', '8796', '--bind', '127.0.0.1'], {stdio: 'ignore'});
  let browser;
  try {
    browser = await chromium.launch({channel: 'chrome', headless: true});
    const page = await browser.newPage({viewport: {width: 1280, height: 1100}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route(/script\.google|script\.googleusercontent|\.mp4/, route => route.abort());
    await page.addInitScript(() => {
      localStorage.setItem('llm-user-name', 'Preview');
      localStorage.setItem('llm-explorer-progress', JSON.stringify({activeSection: 'paceofchange', visited: ['paceofchange'], completed: []}));
    });
    await page.goto(base + '/index.html');
    const game = page.locator('.doubling-game');
    const shell = page.locator('.interactive-box').filter({has: game});
    const input = year => game.getByRole('textbox', {name: 'End of ' + year});
    const result = year => game.locator(`[data-year="${year}"] .doubling-answer`);
    const total = () => game.locator('.doubling-year--current .doubling-total').innerText();
    await game.waitFor();
    await page.evaluate(() => document.fonts.ready);
    await page.clock.install();
    await page.addStyleTag({content: '.no-print:has(> .sticky-inner){visibility:hidden!important}'});
    fs.mkdirSync('tmp/doubling-game', {recursive: true});
    assert.equal(await game.getByRole('textbox').count(), 3);
    assert.equal(await game.getByRole('slider').count(), 0);
    assert.equal(await game.getByRole('button', {name: /^(Next four months|Zoom in|Show all)$/}).count(), 0);
    assert.equal(await game.locator('.doubling-caption, .doubling-view-label, .doubling-zoom-controls').count(), 0);
    assert.equal(await game.locator('.doubling-burgers').count(), 1);
    assert.equal(await game.locator('.doubling-total').count(), 0, 'Totals wait for the animation');
    assert.equal(await game.locator('.doubling-readout').count(), 0, 'No duplicate readout above the burgers');
    assert.equal(await page.getByRole('link', {name: 'Read the study', exact: true}).count(), 0);
    assert.equal(await page.getByRole('heading', {name: 'TRY IT: How Fast is AI Changing'}).count(), 1);
    assert.equal(await shell.locator('.activity-instructions > li').count(), 3);
    const guessesBox = await game.locator('form').boundingBox();
    const burgersBox = await game.locator('.doubling-burgers').boundingBox();
    assert.ok(guessesBox.x + guessesBox.width < burgersBox.x, 'Guesses sit to the left of the burgers on desktop');
    await shell.screenshot({path: 'tmp/doubling-game/burgers-desktop-start.png'});
    await game.getByRole('button', {name: 'Lock in my guesses'}).click();
    assert.equal(await game.locator('[aria-invalid="true"]').count(), 3);
    assert.ok(await input(2027).evaluate(el => el === document.activeElement));
    for (const invalid of ['-1', '1.5', '1,00', 'abc', ' ', '99999999999999999999']) {
      await input(2027).fill(invalid);
      await game.getByRole('button', {name: 'Lock in my guesses'}).click();
      assert.equal(await input(2027).getAttribute('aria-invalid'), 'true', `Reject ${invalid}`);
      assert.equal(await game.getAttribute('data-playing'), 'false');
    }
    await input(2027).fill('8');
    await input(2029).fill('100');
    await input(2031).fill('40,000');
    const lockBox = await game.getByRole('button', {name: 'Lock in my guesses'}).boundingBox();
    await game.getByRole('button', {name: 'Lock in my guesses'}).click();
    assert.equal(await game.getByRole('textbox').count(), 3, 'All guess fields stay visible');
    assert.ok(await game.getByRole('textbox').evaluateAll(nodes => nodes.every(el => el.readOnly)), 'All guesses lock together');
    assert.equal(await game.locator('.doubling-answer').count(), 0, 'Answers wait for milestones');
    await page.clock.runFor(3000);
    assert.equal(await game.getAttribute('data-step'), '0', 'Locking guesses does not start the animation');
    assert.equal(await game.locator('.doubling-view').getAttribute('data-visible'), '1', 'The game still starts with one burger');
    assert.equal(await game.getAttribute('data-playing'), 'false');
    assert.ok(await game.getByRole('button', {name: 'Continue to 2027'}).evaluate(el => el === document.activeElement));
    assert.equal(await game.locator('[data-year="2026"]').count(), 0);
    assert.equal(await input(2027).inputValue(), '8');
    assert.deepEqual(await game.locator('.doubling-year label').allTextContents(), ['End of 2027', 'End of 2029', 'End of 2031']);
    const continueBox = await game.getByRole('button', {name: 'Continue to 2027'}).boundingBox();
    const firstYearBox = await game.locator('[data-year="2027"]').boundingBox();
    assert.equal(continueBox.x, lockBox.x, 'Continue uses the lock button position');
    assert.equal(continueBox.y, lockBox.y);
    assert.ok(continueBox.y + continueBox.height < firstYearBox.y, 'Three year sections sit below the button');
    assert.equal(await game.getByText('Starting total', {exact: true}).count(), 0);
    await shell.screenshot({path: 'tmp/doubling-game/burgers-desktop-locked.png'});
    const view = game.locator('.doubling-view');
    await game.getByRole('button', {name: 'Continue to 2027'}).focus();
    await page.keyboard.press('Enter');
    for (let step = 1; step <= 3; step++) {
      await page.clock.runFor(700);
      assert.equal(Number((await total()).replaceAll(',', '')), 2 ** step);
      assert.equal(await game.locator('.doubling-year--current label').innerText(), 'End of 2027');
      if (step < 3) assert.equal(await game.locator('.doubling-year--current .doubling-date').innerText(), ['End of April 2027', 'End of August 2027'][step - 1]);
      else assert.equal(await game.locator('.doubling-year--current .doubling-date').count(), 0);
    }
    assert.equal(await total(), '8');
    assert.match(await result(2027).innerText(), /8\s+cheeseburgers/);
    assert.equal(await result(2029).count(), 0);
    assert.equal(await game.getAttribute('data-playing'), 'false');
    await shell.screenshot({path: 'tmp/doubling-game/burgers-desktop-2027.png'});
    await game.getByRole('button', {name: 'Continue to 2029'}).click();
    await page.clock.runFor(700 * 6 + 1000);
    assert.equal(await game.getAttribute('data-step'), '9', 'Autoplay stops for the 2029 comparison');
    assert.equal(await total(), '512');
    assert.match(await result(2029).innerText(), /512\s+cheeseburgers/);
    assert.equal(await result(2031).count(), 0);
    assert.equal(await view.getAttribute('data-view-span'), '32', 'Camera zooms out to fit all burgers');
    assert.equal(await view.getAttribute('data-visible'), '512');
    await shell.screenshot({path: 'tmp/doubling-game/burgers-desktop-2029.png'});
    await game.getByRole('button', {name: 'Continue to 2031'}).click();
    await page.clock.runFor(700);
    await game.getByRole('button', {name: 'Pause', exact: true}).click();
    const pausedStep = await game.getAttribute('data-step');
    await page.clock.runFor(3000);
    assert.equal(await game.getAttribute('data-step'), pausedStep, 'Pause stops the animation');
    await game.getByRole('button', {name: 'Play', exact: true}).click();
    await page.clock.runFor(700 * 6 + 1000);
    assert.equal(await game.getAttribute('data-step'), '15');
    assert.equal(await total(), '32,768');
    assert.deepEqual(await game.locator('.doubling-guesses .doubling-total').allTextContents(), ['8', '512', '32,768'], 'Completed totals remain in the three year sections');
    assert.match(await result(2031).innerText(), /32,768\s+cheeseburgers/);
    assert.doesNotMatch(await game.innerText(), /too low|too high|Exactly right/);
    await input(2027).focus();
    await page.keyboard.type('999');
    assert.equal(await input(2027).inputValue(), '8', 'Locked guesses cannot be edited');
    assert.equal(await view.getAttribute('data-visible'), '32768', 'Changing date restores the full view');
    assert.equal(await game.locator('.doubling-burgers').count(), 1, 'A single canvas handles the complete collection');
    assert.equal(Number(await view.getAttribute('data-columns')) * Number(await view.getAttribute('data-rows')), 32768);
    assert.equal(await game.getAttribute('data-playing'), 'false');
    assert.match(await game.innerText(), /They don’t forecast the future/);
    for (const width of [1280, 540, 390, 320]) {
      await page.setViewportSize({width, height: 1100});
      assert.ok(await shell.evaluate(el => el.scrollWidth <= el.clientWidth && el.getBoundingClientRect().right <= innerWidth), `No overflow at ${width}`);
      assert.ok(await game.locator('.doubling-total').evaluateAll(nodes => nodes.every(el => el.scrollWidth <= el.clientWidth && el.clientHeight <= Math.ceil(parseFloat(getComputedStyle(el).fontSize) * 1.3))), `Full total fits on one line at ${width}`);
      await shell.screenshot({path: `tmp/doubling-game/burgers-${width}-complete.png`});
    }
    await game.getByRole('button', {name: 'Play again'}).click();
    assert.equal(await game.locator('.doubling-total').count(), 0, 'Totals wait for the animation');
    assert.equal(await game.locator('.doubling-readout').count(), 0, 'No duplicate readout above the burgers');
    assert.equal(await game.locator('.doubling-answer').count(), 0);
    assert.ok(await input(2027).evaluate(el => el === document.activeElement));
    assert.ok(await input(2027).isEditable(), 'Replay unlocks guesses');
    assert.deepEqual(await game.getByRole('textbox').evaluateAll(nodes => nodes.map(el => el.value)), ['', '', '']);
    const mobileGuesses = await game.locator('form').boundingBox();
    const mobileBurgers = await game.locator('.doubling-burgers').boundingBox();
    assert.ok(mobileGuesses.y + mobileGuesses.height < mobileBurgers.y, 'Guesses and burgers stack on phones');
    await shell.screenshot({path: 'tmp/doubling-game/burgers-mobile-start.png'});
    await page.emulateMedia({reducedMotion: 'reduce'});
    for (const year of [2027, 2029, 2031]) await input(year).fill('0');
    await input(2031).press('Enter');
    await page.clock.runFor(5000);
    assert.equal(await game.getAttribute('data-step'), '0', 'Reduced motion starts paused; zero is a valid guess');
    await game.getByRole('button', {name: 'Continue to 2027'}).click();
    await page.clock.runFor(700);
    assert.equal(await total(), '2');
    await page.goto(base + '/?print=lesson:paceofchange');
    await page.emulateMedia({media: 'print'});
    await game.waitFor({state: 'attached'});
    assert.equal(await game.isVisible(), false);
    assert.equal(await page.getByRole('link', {name: 'Read the study', exact: true}).count(), 0, 'Research intro is excluded from content-only exports');
    assert.deepEqual(errors, []);
    console.log('PASS: three typed guesses, validation, exact year-end totals, staged reveals, pause/resume, automatic zoom, simplified controls, exact one-burger-per-cell scale, keyboard, replay, reduced motion, mobile, print, and no runtime errors.');
  } finally {
    if (browser) await browser.close();
    if (server) server.kill();
  }
})().catch(error => {console.error(error); process.exitCode = 1;});
